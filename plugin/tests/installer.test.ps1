$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent
$installer = Join-Path $projectRoot 'Install-RPGMToolkit.ps1'
$fixtureRoot = Join-Path $PSScriptRoot ('installer-fixtures-' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $fixtureRoot | Out-Null
$encoding = New-Object Text.UTF8Encoding($false)
$checks = 0
function Assert-Test([bool]$Condition, [string]$Name) {
    if (-not $Condition) { throw "FAIL: $Name" }
    $script:checks++
    Write-Output "PASS: $Name"
}
function Run-Installer([string]$Target, [string[]]$Options, [int]$Expected = 0) {
    $output = & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $installer -GamePath $Target @Options 2>&1
    if ($LASTEXITCODE -ne $Expected) { throw "Unexpected installer result $LASTEXITCODE (expected $Expected): $output" }
}
function Read-Plugins([string]$File) {
    $match = [regex]::Match([IO.File]::ReadAllText($File), '(?s)\$plugins\s*=\s*(\[.*\])\s*;?\s*$')
    $parsed = ConvertFrom-Json $match.Groups[1].Value
    return $parsed
}
foreach ($engine in @('MV','MZ')) {
    $game = Join-Path $fixtureRoot $engine
    $root = if ($engine -eq 'MV') { Join-Path $game 'www' } else { $game }
    $js = Join-Path $root 'js'
    New-Item -ItemType Directory -Path (Join-Path $js 'plugins') -Force | Out-Null
    [IO.File]::WriteAllText((Join-Path $js $(if ($engine -eq 'MV') { 'rpg_core.js' } else { 'rmmz_core.js' })), '// fixture', $encoding)
    $list = Join-Path $js 'plugins.js'
    $original = '// Generated by RPG Maker.' + "`r`n" + 'var $plugins = [{"name":"ExistingPlugin","status":true,"description":"Test","parameters":{"Script":"a\\nb","Nested":"{\"key\":\"value\"}"}}];' + "`r`n"
    [IO.File]::WriteAllText($list, $original, $encoding)
    $originalHash = (Get-FileHash -LiteralPath $list).Hash
    Run-Installer $game @('-Preview')
    Assert-Test ((Get-FileHash -LiteralPath $list).Hash -eq $originalHash) "$engine preview makes no change"
    Run-Installer $game @('-Yes')
    $plugins = @(Read-Plugins $list)
    Assert-Test ($plugins.Count -eq 2 -and $plugins[1].name -eq 'RPGMToolkit' -and $plugins[1].status) "$engine installed last and enabled"
    Assert-Test ($plugins[0].parameters.Script -ceq 'a\nb' -and $plugins[0].parameters.Nested -ceq '{"key":"value"}') "$engine preserves existing nested parameters"
    $copy = Join-Path $js 'plugins/RPGMToolkit.js'
    Assert-Test ((Get-FileHash -LiteralPath $copy).Hash -eq (Get-FileHash -LiteralPath (Join-Path $projectRoot 'RPGMToolkit.js')).Hash) "$engine plugin hash matches"
    $backups = @(Get-ChildItem -LiteralPath (Join-Path $root 'RPGMToolkit-backups') -Directory)
    Assert-Test ((Get-FileHash -LiteralPath (Join-Path $backups[0].FullName 'plugins.js')).Hash -eq $originalHash) "$engine exact original backup"
    Run-Installer $game @('-Yes')
    $plugins = @(Read-Plugins $list)
    Assert-Test ($plugins.Count -eq 2) "$engine repeat install has no duplicate"
    # Uninstall must retain plugins added after installation.
    $extra = [pscustomobject]@{name='LaterPlugin';status=$true;parameters=[pscustomobject]@{data='keep'}}
    [IO.File]::WriteAllText($list, ('var $plugins = ' + (ConvertTo-Json -InputObject @($plugins + $extra) -Depth 100) + ';'), $encoding)
    Run-Installer $game @('-Uninstall','-Yes')
    $plugins = @(Read-Plugins $list)
    Assert-Test ($plugins.Count -eq 2 -and $plugins[1].name -eq 'LaterPlugin') "$engine uninstall retains later plugins"
    Assert-Test (-not (Test-Path -LiteralPath $copy)) "$engine uninstall removes only Toolkit JS"
    Run-Installer $game @('-Uninstall','-Yes')
    Assert-Test (@(Read-Plugins $list).Count -eq 2) "$engine repeated uninstall is harmless"
    [IO.File]::WriteAllText($list, 'var $plugins = generatePlugins();', $encoding)
    $badHash = (Get-FileHash -LiteralPath $list).Hash
    Run-Installer $game @('-Yes') 1
    Assert-Test ((Get-FileHash -LiteralPath $list).Hash -eq $badHash) "$engine nonstandard JS rejected without edits"
    [IO.File]::WriteAllText($list, 'var $plugins = [];', $encoding)
    Run-Installer $game @('-Yes')
    Assert-Test (@(Read-Plugins $list).Count -eq 1) "$engine empty plugin list installs correctly"
    $literal = @'
var $plugins = [{name:'ExistingPlugin',status:true,parameters:{value:'\\c[6]',nested:'{"key":"value"}',},},];
'@
    [IO.File]::WriteAllText($list, $literal, $encoding)
    Run-Installer $game @('-Yes')
    $literalPlugins = @(Read-Plugins $list)
    Assert-Test ($literalPlugins.Count -eq 2 -and $literalPlugins[0].parameters.value -ceq '\c[6]' -and $literalPlugins[0].parameters.nested -ceq '{"key":"value"}') "$engine accepts JavaScript literals without altering escapes"
}
Write-Output "All $checks installer assertions passed in Windows PowerShell $($PSVersionTable.PSVersion)."
